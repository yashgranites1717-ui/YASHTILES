export function buildSeed(): Product[] {
  return SEED.trim()
    .split('\n')
    .map((line, i) => {
      const k = line.indexOf('|');
      const code = line.slice(0, k).trim();
      const name = line.slice(k + 1).trim();
      let sq = 0;
      let chk = false;
      let pics = 0;
      const ms = [...name.matchAll(/(\d+)\s*[xX*]\s*(\d+)/g)];
      const m = ms[ms.length - 1];
      if (m) {
        const a = +m[1];
        const b = +m[2];
        const inch = Math.max(a, b) >= 10;
        const per = inch ? (a * b) / 144 : a * b;
        const pm = name.match(/\((\d+)\s*pic\)/i);
        pics = pm ? +pm[1] : 0;
        const key = `${a}x${b}`;
        if (!pics) {
          pics = DEFAULT_PICS_BY_SIZE[key] || 0;
          if (pics) chk = true;
        }
        if (pics) {
          sq = Math.round(per * pics * 100) / 100;
          if (key === '16x16' || key === '20x20' || key === '32x64' || key === '32x94') {
            chk = true;
          }
        }
      }
      return {
        id: 1000 + i,
        code,
        name,
        group: 'tiles' as GroupId,
        sqftPerBox: sq,
        rate: 0,
        chk,
        pics,
      };
    });
}
